-- Auto create dir when saving a file, in case some intermediate directory does not exist
vim.api.nvim_create_autocmd({ "BufWritePre" }, {
  group = augroup("auto_create_dir"),
  callback = function(event)
    if event.match:match("^%w%w+:[\\/][\\/]") then
      return
    end
    local file = vim.uv.fs_realpath(event.match) or event.match
    vim.fn.mkdir(vim.fn.fnamemodify(file, ":p:h"), "p")
  end,
})

-- Reload Files
-- Source - https://stackoverflow.com/a/72504767
function _G.ReloadConfig()
  for name,_ in pairs(package.loaded) do
    if name:match('^config') and not name:match('nvim-tree') then
      package.loaded[name] = nil
    end
  end

  dofile(vim.env.MYVIMRC)
  vim.notify("Pasta config recarregada.", vim.log.levels.INFO)
end

-- treesitter folding and start in file
vim.api.nvim_create_autocmd("FileType", {
  group = augroup("treesitter_indent"),
  pattern = { "html", "css", "lua", "python", "java", "regex", "bash", "json" },
  callback = function()
    vim.treesitter.start()

    vim.wo[0][0].foldexpr = 'v:lua.vim.treesitter.foldexpr()'
    vim.wo[0][0].foldmethod = 'expr'
  end
})

